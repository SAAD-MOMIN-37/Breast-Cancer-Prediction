import { CancerPrediction } from '../api/cancer'

interface ResultsCardProps {
  prediction: CancerPrediction
}

export default function ResultsCard({
  prediction,
}: ResultsCardProps) {
  const isMalignant = prediction.diagnosis === 'Malignant'

  const confidence = Math.round(
    prediction.confidence * 100
  )

  const benign = Math.round(
    prediction.prob_benign * 100
  )

  const malignant = Math.round(
    prediction.prob_malignant * 100
  )

  return (
    <div className="results-card">
      <div className="result-topline">
        <span className="eyebrow">
          MODEL RESULT
        </span>

        <span
          className={`result-status ${
            isMalignant ? 'danger' : 'safe'
          }`}
        >
          {isMalignant
            ? 'REVIEW'
            : 'LOW RISK SIGNAL'}
        </span>
      </div>

      <div
        className={`diagnosis-icon ${
          isMalignant
            ? 'danger-icon'
            : 'safe-icon'
        }`}
      >
        {isMalignant ? '!' : '✓'}
      </div>

      <p className="result-label">
        Predicted Classification
      </p>

      <h2
        className={`diagnosis-title ${
          isMalignant
            ? 'danger-text'
            : 'safe-text'
        }`}
      >
        {prediction.diagnosis}
      </h2>

      <div className="confidence-card">
        <div>
          <span>Model confidence</span>
          <strong>{confidence}%</strong>
        </div>

        <div className="confidence-track">
          <div
            className={`confidence-fill ${
              isMalignant
                ? 'danger-fill'
                : 'safe-fill'
            }`}
            style={{
              width: `${confidence}%`,
            }}
          />
        </div>
      </div>

      <div className="probability-section">
        <div className="probability-title">
          <span>Probability distribution</span>
          <span>100%</span>
        </div>

        <div className="probability-row">
          <div className="probability-label">
            <span className="legend safe-dot" />
            <span>Benign</span>
            <strong>{benign}%</strong>
          </div>

          <div className="probability-track">
            <div
              className="probability-fill safe-fill"
              style={{
                width: `${benign}%`,
              }}
            />
          </div>
        </div>

        <div className="probability-row">
          <div className="probability-label">
            <span className="legend danger-dot" />
            <span>Malignant</span>
            <strong>{malignant}%</strong>
          </div>

          <div className="probability-track">
            <div
              className="probability-fill danger-fill"
              style={{
                width: `${malignant}%`,
              }}
            />
          </div>
        </div>
      </div>

      <div className="medical-note">
        <strong>Important</strong>

        <p>
          This prediction is generated by a
          machine-learning model and must not be
          used as a clinical diagnosis.
        </p>
      </div>
    </div>
  )
}